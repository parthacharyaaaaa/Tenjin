from datetime import datetime
from typing import Protocol


class SupportsBasicKeyData(Protocol):
    @property
    def public_pem(self) -> bytes: ...
    @property
    def kid(self) -> str: ...
    @property
    def alg(self) -> str: ...
    @property
    def curve(self) -> str: ...
    @property
    def epoch(self) -> datetime: ...
